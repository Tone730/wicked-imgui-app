"""Apply the Wicked ImGui Maker rebrand to the extracted Electron app.

Compatibility note: identifiers and filenames stored inside the encrypted
runtimes.pak (kavro.h, Kavro.cs, Kavro type names, the KVRT1 magic and the
"kavro-runtime:" HMAC label) are preserved with placeholders so generated
projects continue to work against the shipped runtime payload.
"""

from __future__ import annotations

import pathlib
import re

ROOT = pathlib.Path(r'C:\Users\Wick\WickedImguiMaker\app')

PROTECT = [
    'KAVRO_IMPLEMENTATION',
    'kavro-runtime:',
    'KVRT1',
    'kavro_win32.h',
    'kavro_assets.h',
    'kavro_impl.cpp',
    'kavro.h',
    'kavro.rs',
    'KavroConfigure',
    'KavroRegisterAssets',
    'KavroUI',
    'KavroProject',
    'KavroApp',
    'Kavro.cs',
    'crate::kavro',
]

REPLACEMENTS = [
    ('support@kavro.pro', 'support@wicked.dev'),
    ('kavro.pro', 'wicked.dev'),
    ('KavroUpdate', 'WickedUpdate'),
    ('Kavro-Setup', 'Wicked-Setup'),
    ('Kavro Projects', 'Wicked Projects'),
    ('Kavro Bot', 'Wicked Bot'),
    ('KAVRO_DISCORD_DEBUG', 'WICKED_DISCORD_DEBUG'),
    ('KAVRO_API_URL', 'WICKED_API_URL'),
    ('KAVRO_LICENSE_KEY', 'WICKED_LICENSE_KEY'),
    ('KAVRO_RELEASE_KEY', 'WICKED_RELEASE_KEY'),
    ('kavroBotSound', 'wickedBotSound'),
    ('kavroBot', 'wickedBot'),
    ('kavroFileNames', 'wickedFileNames'),
    ('defaultKavroDir', 'defaultWickedDir'),
    ('kavroBirth', 'wickedBirth'),
    ('application/x-kavro', 'application/x-wicked'),
    ('project.kavro', 'project.wicked'),
    ('.kavro-backup', '.wicked-backup'),
    ('kavro://', 'wicked://'),
    ('kavro:', 'wicked:'),
    ('window.kavro', 'window.wicked'),
    ("window['kavro']", "window['wicked']"),
    ("'kavro.config'", "'wicked.config'"),
    ('kavro-machine:', 'wicked-machine:'),
    ('kavro-device:', 'wicked-device:'),
    ('kavro-runtime:', 'kavro-runtime:'),
    ('Kavro', 'Wicked'),
    ('kavro', 'wicked'),
    ('KAVRO', 'WICKED'),
]

# Files whose source contains generated-code identifiers that must not change.
CODEGEN_FILES = {'builder.cjs', 'integrate.cjs', 'integrate.js', 'runtime-pak.cjs', 'customcode.js'}
TEXT_SUFFIXES = {'.js', '.cjs', '.html', '.css', '.json', '.md', '.txt', '.svg'}

protect_tokens: dict[str, str] = {}
for i, token in enumerate(PROTECT):
    ph = f'__WIM_PROTECT_{i}__'
    protect_tokens[token] = ph


def apply(text: str, path: pathlib.Path) -> str:
    for token, ph in protect_tokens.items():
        text = text.replace(token, ph)

    # Protect standalone generated-code type names in codegen-related files.
    protect_type = (
        'shared' in path.parts and 'codegen' in path.parts
    ) or path.name in CODEGEN_FILES
    if protect_type:
        text = re.sub(r'\bKavro\b', '__WIM_RT_TYPE_ID__', text)

    for old, new in REPLACEMENTS:
        text = text.replace(old, new)

    if protect_type:
        text = text.replace('__WIM_RT_TYPE_ID__', 'Kavro')

    for token, ph in protect_tokens.items():
        text = text.replace(ph, token)

    # Cosmetic cleanup in generated-code comments after restoring identifiers.
    text = text.replace('generated by Kavro', 'generated by Wicked ImGui Maker')
    text = text.replace('Generated by Kavro', 'Generated by Wicked ImGui Maker')
    text = text.replace('[kavro]', '[wicked]')
    return text


changed = 0
for path in sorted(ROOT.rglob('*')):
    if not path.is_file() or path.suffix not in TEXT_SUFFIXES:
        continue
    if 'vendor' in path.parts or 'node_modules' in path.parts:
        continue
    before = path.read_text(encoding='utf-8', errors='replace')
    after = apply(before, path)
    if after != before:
        path.write_text(after, encoding='utf-8')
        changed += 1

old_dir = ROOT / 'src' / 'renderer' / 'js' / 'kavro-bot'
new_dir = ROOT / 'src' / 'renderer' / 'js' / 'wicked-bot'
if old_dir.exists():
    if new_dir.exists():
        raise SystemExit(f'{new_dir} already exists')
    old_dir.rename(new_dir)

print(f'rebranded {changed} files')
