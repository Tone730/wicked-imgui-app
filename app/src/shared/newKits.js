// Float RGBA values from the sources are kept as floats and converted here so
// the exact source numbers remain auditable. This module is data-only.

// Float channel -> two-digit hex. Sources use 0..1 floats; a few use 0..255 ints.
const hx = (n) => Math.round(Math.max(0, Math.min(1, Number(n)) * 255)).toString(16).padStart(2, '0').toUpperCase();
const rgba = (r, g, b, a = 1) => '#' + hx(r) + hx(g) + hx(b) + hx(a);
const i2h = (n) => Math.round(Math.max(0, Math.min(255, Number(n)))).toString(16).padStart(2, '0').toUpperCase();
const hex255 = (r, g, b, a = 255) => '#' + i2h(r) + i2h(g) + i2h(b) + i2h(a);

